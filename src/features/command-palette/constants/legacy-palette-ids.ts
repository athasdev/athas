const legacySettingsTabPrefix = "open-settings-tab-";

export function migrateLegacyPaletteId(id: string): string {
  if (id.startsWith(legacySettingsTabPrefix)) {
    return `preferences.openSettingsTab.${id.slice(legacySettingsTabPrefix.length)}`;
  }

  return legacyPaletteIds[id] ?? id;
}
